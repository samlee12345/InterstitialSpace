// An experience's photos: three thumbnails (the third shows "+N" over it when there are
// more); selecting one opens them full size, one at a time (round 29).
function ExpPhotos({ photos, by }) {
  const { get } = useDemo();
  const [open, setOpen] = useState(null);
  const more = photos.length > 3 ? photos.length - 2 : 0;
  const ph = open === null ? null : photos[open];
  const step = (d) => setOpen((open + d + photos.length) % photos.length);
  return (
    <>
      <div className="exp-photos" aria-label={`${photos.length} photos`}>
        {photos.slice(0, 3).map((p, i) => (
          <button key={p.id} type="button" className="exp-photo" onClick={() => setOpen(i)} aria-label={i === 2 && more ? `See all ${photos.length} photos` : `Open photo ${i + 1}${p.alt ? `: ${p.alt}` : ''}`}>
            <ImageBox label="Photo" shape="square" src={p.src} alt="" />
            {i === 2 && more > 0 && <span className="exp-photo-more" aria-hidden="true">+{more}</span>}
          </button>
        ))}
      </div>
      {ph && (
        <Modal title={`Photo ${open + 1} of ${photos.length}`} onClose={() => setOpen(null)} wide>
          <div className="photo-view"><ImageBox label={`Photo ${open + 1}`} src={ph.src} alt={ph.alt} fit="contain" /></div>
          <p className="small muted">{ph.alt ? `${ph.alt}. ` : ''}By {get.user(by)?.name || 'a member'}.</p>
          {photos.length > 1 && (
            <FormActions>
              <Button onClick={() => step(-1)}>Previous</Button>
              <Button onClick={() => step(1)}>Next</Button>
            </FormActions>
          )}
        </Modal>
      )}
    </>
  );
}

// ── Report an update: the space has changed on the ground ───
function ReportUpdate({ space, onClose }) {
  // Round 32: the reporter only says what changed; the moderator decides whether it's the
  // build of a contest's winning design.
  const { dispatch, user } = useDemo();
  const [sent, setSent] = useState(false);
  const [text, setText] = useState('');
  const [photos, setPhotos] = useState(0);
  const [err, setErr] = useState({});
  const send = () => {
    const e = {};
    if (text.trim().length < 15) e.text = 'Describe what changed, in a sentence or two.';
    if (!photos) e.photos = 'Add at least one photo of the space as it is now.';
    setErr(e);
    if (Object.keys(e).length) return;
    dispatch({ type: 'REPORT_UPDATE', spaceId: space.id, userId: user.id, text: text.trim(), photos });
    setSent(true);
  };
  if (sent) {
    return (
      <Modal title="Update received" onClose={onClose}>
        <p>Thanks. Your update and {photos} photo{photos === 1 ? '' : 's'} were sent to the moderators to approve.</p>
        <p className="small muted">We’ll notify you when they decide. If they confirm it, everything contributed before the update moves to the Archived tab.</p>
        <FormActions><Button variant="primary" onClick={onClose}>Done</Button></FormActions>
      </Modal>
    );
  }
  return (
    <Modal title="Report an update" onClose={onClose} wide>
      <p className="small">Has {space.name} been rebuilt, repaired or changed? Show what it looks like now. If a moderator confirms it, everything contributed so far (votes, photos, experiences, diagrams and redesigns) moves to the Archived tab and the space starts fresh.</p>
      <Input label={<>What changed?<span className="req" aria-hidden="true"> *</span></>} textarea value={text} onChange={(e) => setText(e.target.value)} error={err.text} placeholder="e.g. The steps were rebuilt in stone and a handrail was added in October." />
      <div className="field">
        <span className="label">Proof: photos of the space now<span className="req" aria-hidden="true"> *</span></span>
        <div className="thumbs">{Array.from({ length: photos }, (_, i) => <ImageBox key={i} label={`${i + 1}`} shape="square" />)}</div>
        <div className="row">
          <Button onClick={() => setPhotos(photos + 1)}><Icon name="photo" />Take a photo</Button>
          <Button onClick={() => setPhotos(photos + 1)}>Choose from library</Button>
        </div>
        {err.photos && <span className="error" role="alert">{err.photos}</span>}
        <span className="xs muted">Photos need location data so moderators can check they were taken here.</span>
      </div>
      <FormActions><Button onClick={onClose}>Cancel</Button><Button variant="primary" onClick={send}>Submit update</Button></FormActions>
    </Modal>
  );
}

