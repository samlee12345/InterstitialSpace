// Names in a short sentence: "A, B and 3 others".
const nameList = (names, max = 2) => (names.length <= max + 1 ? names.join(', ').replace(/, ([^,]*)$/, ' and $1') : `${names.slice(0, max).join(', ')} and ${names.length - max} others`);

// In the tabs view the tab names the section and carries the count, so no heading here.
function SectionHead({ id, title, note, children }) {
  return (
    <div className="row between">
      <div className="stack-sm">
        <h2 id={id} className="visually-hidden">{title}</h2>
        {note && <p className="small muted">{note}</p>}
      </div>
      <div className="row">{children}</div>
    </div>
  );
}

// ── Base Library (round 32): what the AI makes from a space's photos and experiences:
// spatial diagrams and one 3D model. Members don't upload these (drawings go on an
// experience); anyone, signed in or not, downloads them free.
export const MODEL_FILES = ['.obj', '.fbx', '.glb', '.3dm', '.skp', '.e57', '.ply'];

function BaseLibrary({ space }) {
  const { state, dispatch, cfg, get } = useDemo();
  const diagrams = space.diagrams.filter((d) => d.source === 'ai');
  const model = state.models.find((m) => m.spaceId === space.id && !m.takenDown && !m.archived);
  const aiPending = diagrams.length === 0 && space.photos.length >= cfg.aiDiagramMinPhotos;
  const people = [...new Set(space.photos.map((p) => p.credit).filter(Boolean))].map((id) => get.user(id)?.name).filter(Boolean);
  const from = `from ${space.photos.length} photo${space.photos.length === 1 ? '' : 's'}${people.length ? ` by ${nameList(people)}` : ''}`;
  const download = (what) => dispatch({ type: 'TOAST', text: `Downloaded ${what}. Free to use; credit the contributors.` });

  // Simulated AI: a space with enough photos shows "Processing…", then its diagram.
  useEffect(() => {
    if (!aiPending) return undefined;
    const t = setTimeout(() => dispatch({ type: 'AI_DIAGRAM', spaceId: space.id }), 4000);
    return () => clearTimeout(t);
  }, [aiPending, space.id, dispatch]);

  return (
    <section className="stack" data-screen-label="Base Library" aria-labelledby="library-heading">
      <SectionHead id="library-heading" title="Base Library" note="Spatial diagrams and a 3D model, generated by AI from members’ photos and experiences. Free for anyone to download and use. Have a drawing of your own? Add it to your experience." />
      <section className="stack-sm" aria-labelledby="lib-diagrams-h">
        <h3 id="lib-diagrams-h" className="h-sm">Spatial diagrams ({diagrams.length})</h3>
        {aiPending && (
          <div className="card">
            <div className="row"><div className="spinner" aria-hidden="true" /><h4>Processing…</h4></div>
            <p>This space has {space.photos.length} photos, so the AI is drawing a spatial diagram from them.</p>
          </div>
        )}
        {!aiPending && diagrams.length === 0 && <p className="note">The AI draws a diagram once a space has {cfg.aiDiagramMinPhotos} photos. This one has {space.photos.length}.</p>}
        {diagrams.map((d, i) => (
          <article key={d.id} className="stack-sm diagram-set" aria-label={`Spatial diagram ${i + 1}`}>
            {d.src ? (
              <figure className="captioned diagram-real">
                <ImageBox label={d.label || 'Spatial diagram'} src={d.src} alt={d.alt} fit="contain" shape="diagram" />
                <figcaption>{d.label ? `${d.label}. ` : ''}Generated by AI {from}.</figcaption>
              </figure>
            ) : (
              <div className="halves">
                <figure className="captioned"><ImageBox label="Plan (placeholder)" /><figcaption>Plan, generated by AI {from}</figcaption></figure>
                <figure className="captioned"><ImageBox label="Section (placeholder)" /><figcaption>Section through the main space</figcaption></figure>
              </div>
            )}
            <div className="row">
              <Button onClick={() => download('the spatial diagram')}>Download diagram (free)</Button>
              <span className="small muted">Plan and section as .pdf and .dwg{d.date ? `. Updated ${d.date}` : ''}.</span>
            </div>
          </article>
        ))}
      </section>
      <section className="stack-sm" aria-labelledby="lib-model-h">
        <h3 id="lib-model-h" className="h-sm">3D model</h3>
        {model ? (
          <>
            <figure className="captioned">
              <ImageBox label="3D model viewer (placeholder): orbit, zoom, section cut" className="model-view" />
              <figcaption>Generated by AI {from}. Updated as people add more.</figcaption>
            </figure>
            <div className="row">
              <Button onClick={() => download('the 3D model')}>Download 3D model (free)</Button>
              <span className="small muted">.obj, .3dm and .skp.</span>
            </div>
          </>
        ) : (
          <p className="note">The AI builds the model once the space has {cfg.aiDiagramMinPhotos} photos. This one has {space.photos.length}.</p>
        )}
      </section>
    </section>
  );
}

// ── Archived: everything from before a confirmed update ─────
function Archived({ space }) {
  const { state, get } = useDemo();
  const rounds = space.archive || [];
  return (
    <section className="stack" data-screen-label="Archived" aria-labelledby="archived-heading">
      <SectionHead id="archived-heading" title={`Archived (${rounds.length})`} note="When a space changes on the ground and a moderator confirms the update, everything contributed before it moves here." />
      {rounds.length === 0 && <Empty title="Nothing archived"><p>This space hasn’t been reported as updated since it was documented.</p></Empty>}
      {rounds.map((r) => {
        const exps = state.comments.filter((c) => c.spaceId === space.id && c.archived === r.date);
        const reds = state.redesigns.filter((x) => x.spaceId === space.id && x.archived === r.date);
        return (
          <article key={r.date} className="card stack-sm">
            <h3 className="h-sm">Before the update on {r.date}</h3>
            <p className="small">{r.reason}</p>
            <p className="small muted">{[[r.votes, 'vote for an upgrade', 'votes for an upgrade'], [r.photos.length, 'photo', 'photos'], [exps.length, 'experience', 'experiences'], [r.diagrams.length, 'spatial diagram', 'spatial diagrams'], [reds.length, 'redesign', 'redesigns']].map(([n, one, many]) => `${n} ${n === 1 ? one : many}`).join(', ')}.</p>
            {exps.length > 0 && (
              <ul className="list small">
                {exps.map((c) => <li key={c.id}><UserLink id={c.userId} you={false} className="bold" />: {c.text}</li>)}
              </ul>
            )}
            {reds.length > 0 && <p className="small">Redesigns: {reds.map((x) => <Link key={x.id} to={`/item/${x.id}`} className="archived-link">{x.title}</Link>)}</p>}
          </article>
        );
      })}
    </section>
  );
}

// ── Redesigns ───────────────────────────────────────────────
function Redesigns({ space }) {
  const { state, isMember, isArchitect, dispatch, rankOf, user, uploadLimit, here } = useDemo();
  const list = state.redesigns
    .filter((r) => r.spaceId === space.id && r.published && !r.takenDown && !r.archived)
    .sort((a, b) => rankOf(a.architectId) - rankOf(b.architectId));
  const limit = isArchitect ? uploadLimit(user.id, space.id) : null;
  return (
    <section className="stack" data-screen-label="Redesigns" aria-labelledby="redesigns-heading">
      <SectionHead id="redesigns-heading" title={`Redesigns (${list.length})`} note="Proposals by architects, paid per download. Architects ranked higher appear first.">
        {(!isArchitect || limit.allowed) && <UploadRedesign space={space} primary />}
        {isArchitect && !limit.allowed && <span className="small muted">You published a redesign for this space this week. You can add another here on {limit.next.toLocaleDateString()}; other spaces are open now.</span>}
      </SectionHead>
      {list.length === 0 && (
        <Empty title="No redesigns yet">
          <p>{isArchitect ? 'Be the first architect to propose one.' : 'Architects have not proposed a redesign for this space yet.'}</p>
        </Empty>
      )}
      {list.length > 0 && isMember && <div className="grid">{list.map((r) => <RedesignCard key={r.id} redesign={r} />)}</div>}
      {list.length > 0 && !isMember && (
        <div className="teaser">
          <div className="grid">{list.map((r) => <RedesignCard key={r.id} redesign={r} blurred />)}</div>
          <div className="teaser-cta">
            <div>
              <h3>{list.length} redesign{list.length > 1 ? 's' : ''} for this space</h3>
              <p className="small">Redesigns are visible to members.</p>
              <Button variant="primary" onClick={() => dispatch({ type: 'OPEN_SIGNUP', reason: 'redesigns', returnTo: here })}>See redesigns</Button>
            </div>
          </div>
        </div>
      )}
    </section>
  );
}

