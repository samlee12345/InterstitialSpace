    experience: state.comments.filter((c) => c.spaceId === space.id && !c.archived).length,
    library: space.diagrams.filter((d) => d.source === 'ai').length + (state.models.some((m) => m.spaceId === space.id && !m.takenDown && !m.archived) ? 1 : 0),
